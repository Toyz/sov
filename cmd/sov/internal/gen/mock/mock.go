// Package mock generates a runnable Go MOCK POD from a sov introspect catalog:
// a gateway that serves every method of every service with a schema-shaped
// example response. Because it is generated from the SAME catalog as the typed
// clients and speaks the identical wire contract (method paths, the {"args"}
// envelope, the {"data"} success shape), a client tested against the mock works
// unchanged against the real pod — the "contract-verifiable mock" that falls out
// of sov's uniform wire contract. Use it to develop/test a consumer before its
// backend exists, or as a stand-in in CI.
package mock

import (
	"fmt"
	"io"
	"sort"
	"strconv"
	"strings"

	"github.com/Toyz/sov/cmd/sov/internal/catalog"
	"github.com/Toyz/sov/cmd/sov/internal/strs"
	"github.com/Toyz/sov/gateway"
	"github.com/Toyz/sov/rpc"
)

// Run executes `sov gen mock [flags]`.
func Run(argv []string, stdout, stderr io.Writer) int {
	return catalog.RunEmitter(catalog.EmitterSpec{
		Name:           "mock",
		DefaultOut:     "./mock/main.go",
		OutHelp:        "output path for the generated mock pod (default ./mock/main.go; - for stdout)",
		DefaultPackage: "main",
		PackageHelp:    "package name for the generated mock (default main)",
		Emit:           Emit,
	}, argv, stdout, stderr)
}

// Emit writes a mock pod for report to w.
func Emit(w io.Writer, pkg string, report *gateway.IntrospectReport) {
	fmt.Fprintln(w, "// Code generated by sovgen — DO NOT EDIT.")
	fmt.Fprintln(w, "//")
	fmt.Fprintln(w, "// Contract mock pod: serves every service method with a schema-shaped example")
	fmt.Fprintln(w, "// response over the identical sov wire contract, so a client works against it")
	fmt.Fprintln(w, "// exactly as against the real backend. Run: go run . -addr :8080")
	fmt.Fprintf(w, "package %s\n\n", pkg)
	fmt.Fprintln(w, "import (")
	fmt.Fprintln(w, "\t\"context\"")
	fmt.Fprintln(w, "\t\"flag\"")
	fmt.Fprintln(w, "\t\"log\"")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "\t\"github.com/Toyz/sov/gateway\"")
	fmt.Fprintln(w, "\trpcsurface \"github.com/Toyz/sov/gateway/builtin/rpc\"")
	fmt.Fprintln(w, "\t\"github.com/Toyz/sov/rpc\"")
	fmt.Fprintln(w, ")")
	fmt.Fprintln(w)

	routers := sortedRouters(report)
	for _, name := range routers {
		emitMockRouter(w, report, name)
	}

	fmt.Fprintln(w, "func main() {")
	fmt.Fprintln(w, "\taddr := flag.String(\"addr\", \":8080\", \"listen address\")")
	fmt.Fprintln(w, "\tflag.Parse()")
	fmt.Fprintln(w, "\tgw := gateway.New()")
	fmt.Fprintln(w, "\tgw.MustUse(rpcsurface.New())")
	for _, name := range routers {
		fmt.Fprintf(w, "\tgw.Register(&%s{})\n", mockType(name))
	}
	// io.WriteString (not Fprintln) so `go vet` doesn't read the emitted %s as a
	// Printf directive for THIS call.
	io.WriteString(w, "\tlog.Printf(\"sov mock listening on %s\", *addr)\n")
	fmt.Fprintln(w, "\tif err := gw.ListenAndServe(context.Background(), *addr); err != nil {")
	fmt.Fprintln(w, "\t\tlog.Fatal(err)")
	fmt.Fprintln(w, "\t}")
	fmt.Fprintln(w, "}")
	// rpc is always referenced by a method receiver's *rpc.Context param as long
	// as a service has at least one method (every real catalog does).
	if !anyMethod(report) {
		fmt.Fprintln(w)
		fmt.Fprintln(w, "var _ = rpc.NewContext // keep the rpc import when the catalog has no methods")
	}
}

func emitMockRouter(w io.Writer, report *gateway.IntrospectReport, router string) {
	// The engine derives the wire router name from the Go type name minus a
	// "Router" suffix, so name the mock "{Service}Router" to register under the
	// EXACT service name — otherwise the mock would serve /rpc/{Type}/... and
	// break the contract it exists to reproduce.
	typ := mockType(router)
	fmt.Fprintf(w, "// %s is a contract mock for the %q service.\n", typ, router)
	fmt.Fprintf(w, "type %s struct{}\n\n", typ)

	seen := map[string]bool{}
	for _, rd := range report.Services[router] {
		for _, md := range rd.Methods {
			if seen[md.Method] {
				continue
			}
			seen[md.Method] = true
			emitMockMethod(w, report, typ, md)
		}
	}
}

// mockType is the Go type name for a service's mock router: "{Service}Router",
// which the engine registers under "{Service}" (it trims the Router suffix).
func mockType(service string) string { return typeIdent(service) + "Router" }

func emitMockMethod(w io.Writer, report *gateway.IntrospectReport, recv string, md rpc.MethodDescriptor) {
	goName := strs.Capitalize(md.Method)
	ex := exampleExpr(report, md.ResponseTypeName, 0)
	if md.Streaming {
		// A streaming method returns rpc.Stream[T]; mock it with a couple of
		// example items so a streaming consumer sees the NDJSON framing.
		fmt.Fprintf(w, "func (%s) %s(_ *rpc.Context) (rpc.Stream[map[string]any], error) {\n", recv, goName)
		fmt.Fprintf(w, "\treturn rpc.StreamSlice([]map[string]any{%s, %s}), nil\n", ex, ex)
		fmt.Fprintln(w, "}")
		fmt.Fprintln(w)
		return
	}
	fmt.Fprintf(w, "func (%s) %s(_ *rpc.Context) (map[string]any, error) {\n", recv, goName)
	fmt.Fprintf(w, "\treturn %s, nil\n", ex)
	fmt.Fprintln(w, "}")
	fmt.Fprintln(w)
}

// exampleExpr returns Go source for a schema-shaped example of the named type,
// recursing into nested named types with a depth guard against cycles.
func exampleExpr(report *gateway.IntrospectReport, typeName string, depth int) string {
	if typeName == "" || depth > 4 {
		return "map[string]any{}"
	}
	td, ok := report.Types[typeName]
	if !ok || len(td.Fields) == 0 {
		return "map[string]any{}"
	}
	var b strings.Builder
	b.WriteString("map[string]any{")
	for i, f := range td.Fields {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q: %s", f.JSONName, fieldExampleExpr(report, f, depth))
	}
	b.WriteString("}")
	return b.String()
}

func fieldExampleExpr(report *gateway.IntrospectReport, f rpc.ParamField, depth int) string {
	switch f.SchemaType {
	case "string":
		if f.Example != "" {
			return strconv.Quote(f.Example)
		}
		return `""`
	case "number", "integer":
		if f.Example != "" {
			if _, err := strconv.ParseFloat(f.Example, 64); err == nil {
				return f.Example
			}
		}
		return "0"
	case "boolean":
		if f.Example == "true" || f.Example == "false" {
			return f.Example
		}
		return "false"
	case "array":
		if f.TypeName != "" {
			return "[]any{" + exampleExpr(report, f.TypeName, depth+1) + "}"
		}
		return "[]any{}"
	case "object":
		if f.TypeName != "" {
			return exampleExpr(report, f.TypeName, depth+1)
		}
		return "map[string]any{}"
	default:
		return "nil"
	}
}

func sortedRouters(report *gateway.IntrospectReport) []string {
	out := make([]string, 0, len(report.Services))
	for name := range report.Services {
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}

func anyMethod(report *gateway.IntrospectReport) bool {
	for _, descs := range report.Services {
		for _, rd := range descs {
			if len(rd.Methods) > 0 {
				return true
			}
		}
	}
	return false
}

// typeIdent turns a service name into a valid, exported Go identifier: keep
// letters/digits, drop the rest, and ensure it starts with an upper-case
// letter. Service names are Go type names in practice, so this is defensive.
func typeIdent(name string) string {
	var b strings.Builder
	for _, r := range name {
		if r == '_' || r >= 'A' && r <= 'Z' || r >= 'a' && r <= 'z' || r >= '0' && r <= '9' {
			b.WriteRune(r)
		}
	}
	s := b.String()
	if s == "" || s[0] >= '0' && s[0] <= '9' {
		s = "Svc" + s
	}
	return strs.Capitalize(s)
}
